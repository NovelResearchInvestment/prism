/** The user's own country, guessed from the system time zone (no network needed). */
export function homeCountry(): string {
  let tz = "";
  try {
    tz = Intl.DateTimeFormat().resolvedOptions().timeZone ?? "";
  } catch {
    /* no Intl */
  }
  const zones: Record<string, string> = {
    "Asia/Shanghai": "CN",
    "Asia/Chongqing": "CN",
    "Asia/Urumqi": "CN",
    "Asia/Harbin": "CN",
    "Asia/Hong_Kong": "HK",
    "Asia/Macau": "MO",
    "Asia/Taipei": "TW",
    "Asia/Tokyo": "JP",
    "Asia/Seoul": "KR",
    "Asia/Singapore": "SG",
    "Asia/Kuala_Lumpur": "MY",
    "Asia/Bangkok": "TH",
    "Asia/Ho_Chi_Minh": "VN",
    "Asia/Manila": "PH",
    "Asia/Jakarta": "ID",
    "Asia/Kolkata": "IN",
    "Asia/Dubai": "AE",
    "Europe/London": "GB",
    "Europe/Berlin": "DE",
    "Europe/Paris": "FR",
    "Europe/Amsterdam": "NL",
    "Europe/Moscow": "RU",
    "Australia/Sydney": "AU",
    "Australia/Melbourne": "AU",
    "Pacific/Auckland": "NZ",
  };
  if (zones[tz]) return zones[tz];
  if (tz.startsWith("America/")) return tz.includes("Toronto") || tz.includes("Vancouver") ? "CA" : "US";
  if (tz.startsWith("Europe/")) return "DE";
  return "CN";
}
